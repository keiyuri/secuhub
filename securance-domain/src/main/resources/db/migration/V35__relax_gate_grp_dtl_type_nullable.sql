-- 코드 리뷰 지적(2026-08-28)/Codex 적대적 리뷰 재지적(2026-08-28): 게이트그룹 수정 화면의
-- "게이트 타입" 선택을 없애면서 GateGroup.gateTypeCode 필드(→ tb_gate_grp.dtl_type 매핑)도
-- 제거했다. 이 마이그레이션은 원래 그 컬럼을 곧바로 DROP했는데, 두 가지 이유로 위험했다:
--
--   1) 롤링 배포(신버전/구버전 인스턴스가 동시에 떠 있는 구간)나 애플리케이션만 구버전으로
--      되돌리는 배포 롤백 상황에서, 구버전 코드는 여전히 이 컬럼에 값을 쓰려 하므로 컬럼이
--      사라진 순간 즉시 실패한다. DROP은 되돌릴 수 없어 이미 삭제된 값도 복구할 수 없다.
--   2) 컬럼을 지우지 않고 그대로 NOT NULL로 남겨 두는 것만으로도 충분하지 않다 — 신버전 코드는
--      이 컬럼에 값을 쓰지 않으므로, NOT NULL 제약이 남아 있으면 신버전의 INSERT가 오히려
--      "Column 'dtl_type' cannot be null"로 실패한다.
--
-- 그래서 이번 마이그레이션은 컬럼을 유지한 채 NOT NULL 제약만 없앤다 — 구버전(계속 값을 씀)과
-- 신버전(값을 쓰지 않음) 코드가 어느 쪽이 실행 중이어도 함께 안전하게 공존할 수 있다. 실제
-- DROP COLUMN은 모든 인스턴스가 신버전으로 전환되고 롤백 가능 기간이 지난 뒤, 사전 백업을 확보한
-- 상태에서 별도의 후속 마이그레이션으로 수행한다.
ALTER TABLE tb_gate_grp MODIFY COLUMN dtl_type INT NULL;
