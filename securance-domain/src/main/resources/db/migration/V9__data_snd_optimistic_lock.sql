-- 상태 저장소가 된다. GateControlDispatcher는 TCP 커넥션을 로컬로 들고 있는 인스턴스만
-- 실제 전송하도록 이미 자체 필터링하지만, 장비 재접속으로 커넥션 소유권이 인스턴스 간에
-- 넘어가는 짧은 틈에는 두 인스턴스가 같은 행을 동시에 갱신하려 할 수 있다.
-- JPA `@Version`이 이 컬럼으로 낙관적 잠금을 걸어, 경합을 조용한 덮어쓰기 대신 명시적인
-- 예외로 바꾼다(DataSend 엔티티 KDoc 참고).
-- ============================================================================

ALTER TABLE tb_data_snd
    ADD COLUMN version BIGINT NOT NULL DEFAULT 0 AFTER snd_tail;
